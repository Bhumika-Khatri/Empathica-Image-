import os
import json
import time
import copy
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path
from PIL import Image

import torch
import torch.nn as nn
from torch.utils.data import DataLoader, Subset
from torchvision import datasets, transforms, models
from torchvision.models import ResNet18_Weights
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, confusion_matrix

# ---------------- SETTINGS ----------------

ROOT = "/content/dataset"
IMG_SIZE = 224
BATCH_SIZE = 64
EPOCHS = 12
SEED = 42

MODEL_PATH = "/content/EMPATHICA_resnet18.pth"
LABEL_PATH = "/content/EMPATHICA_labels.json"

torch.manual_seed(SEED)
np.random.seed(SEED)

device = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)
print("Device:", device)

if device.type == "cuda":
    torch.backends.cudnn.benchmark = True

# ---------------- FIND FOLDERS ----------------

train_candidates = [
    p for p in Path(ROOT).rglob("train") if p.is_dir()
]
test_candidates = [
    p for p in Path(ROOT).rglob("test") if p.is_dir()
]

if not train_candidates or not test_candidates:
    raise ValueError("Train/test folders not found.")

train_path = str(train_candidates[0])
test_path = str(test_candidates[0])

print("Train:", train_path)
print("Test:", test_path)

# ---------------- TRANSFORMS ----------------
# RAF-DB uses color, aligned facial images.
# ImageNet normalization matches the pretrained backbone.

mean = [0.485, 0.456, 0.406]
std = [0.229, 0.224, 0.225]

train_transform = transforms.Compose([
    transforms.RandomResizedCrop(
        IMG_SIZE,
        scale=(0.85, 1.0),
        ratio=(0.9, 1.1)
    ),
    transforms.RandomHorizontalFlip(),
    transforms.RandomRotation(15),
    transforms.ColorJitter(
        brightness=0.3,
        contrast=0.3
    ),
    transforms.ToTensor(),
    transforms.Normalize(mean, std),
    transforms.RandomErasing(
        p=0.25,
        scale=(0.02, 0.15)
    )
])

eval_transform = transforms.Compose([
    transforms.Resize((IMG_SIZE, IMG_SIZE)),
    transforms.ToTensor(),
    transforms.Normalize(mean, std)
])

# Two copies let validation use clean images.
full_train_aug = datasets.ImageFolder(
    train_path, transform=train_transform
)
full_train_eval = datasets.ImageFolder(
    train_path, transform=eval_transform
)
test_dataset = datasets.ImageFolder(
    test_path, transform=eval_transform
)

folder_names = full_train_aug.classes

if test_dataset.classes != folder_names:
    raise ValueError("Train and test classes do not match.")

# Standard RAF-DB numeric labels.
raf_map = {
    "1": "surprise",
    "2": "fear",
    "3": "disgust",
    "4": "happy",
    "5": "sad",
    "6": "angry",
    "7": "neutral"
}

if set(folder_names) == set(raf_map):
    emotion_names = [raf_map[c] for c in folder_names]
else:
    emotion_names = folder_names.copy()

print("Folder order:", folder_names)
print("Emotion order:", emotion_names)
print("Training images:", len(full_train_aug))
print("Test images:", len(test_dataset))

# ---------------- STRATIFIED VALIDATION SPLIT ----------------

targets = np.array(full_train_aug.targets)
indices = np.arange(len(targets))

train_idx, val_idx = train_test_split(
    indices,
    test_size=0.15,
    random_state=SEED,
    stratify=targets
)

train_dataset = Subset(full_train_aug, train_idx)
val_dataset = Subset(full_train_eval, val_idx)

train_loader = DataLoader(
    train_dataset,
    batch_size=BATCH_SIZE,
    shuffle=True,
    num_workers=2,
    pin_memory=(device.type == "cuda")
)

val_loader = DataLoader(
    val_dataset,
    batch_size=BATCH_SIZE,
    shuffle=False,
    num_workers=2,
    pin_memory=(device.type == "cuda")
)

test_loader = DataLoader(
    test_dataset,
    batch_size=BATCH_SIZE,
    shuffle=False,
    num_workers=2,
    pin_memory=(device.type == "cuda")
)

# ---------------- MODEL ----------------

weights = ResNet18_Weights.DEFAULT
model = models.resnet18(weights=weights)

model.fc = nn.Sequential(
    nn.Dropout(0.5),
    nn.Linear(model.fc.in_features, len(emotion_names))
)

model = model.to(device)

criterion = nn.CrossEntropyLoss(label_smoothing=0.1)

optimizer = torch.optim.AdamW(
    model.parameters(),
    lr=1e-4,
    weight_decay=0.01
)

scheduler = torch.optim.lr_scheduler.OneCycleLR(
    optimizer,
    max_lr=1e-3,
    epochs=EPOCHS,
    steps_per_epoch=len(train_loader)
)

use_amp = device.type == "cuda"
scaler = torch.amp.GradScaler("cuda", enabled=use_amp)

# ---------------- TRAINING ----------------

best_val_acc = 0.0
best_state = copy.deepcopy(model.state_dict())

for epoch in range(EPOCHS):
    start = time.time()
    model.train()

    running_loss = 0.0
    correct = 0
    total = 0

    for images, labels in train_loader:
        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        optimizer.zero_grad(set_to_none=True)

        with torch.autocast(
            device_type=device.type,
            dtype=torch.float16,
            enabled=use_amp
        ):
            outputs = model(images)
            loss = criterion(outputs, labels)

        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()
        scheduler.step()

        running_loss += loss.item() * labels.size(0)
        correct += (outputs.argmax(1) == labels).sum().item()
        total += labels.size(0)

    train_loss = running_loss / total
    train_acc = correct / total

    # Validation uses unaugmented images.
    model.eval()
    val_correct = 0
    val_total = 0
    val_loss_sum = 0.0

    with torch.no_grad():
        for images, labels in val_loader:
            images = images.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)

            with torch.autocast(
                device_type=device.type,
                dtype=torch.float16,
                enabled=use_amp
            ):
                outputs = model(images)
                loss = criterion(outputs, labels)

            val_loss_sum += loss.item() * labels.size(0)
            val_correct += (
                outputs.argmax(1) == labels
            ).sum().item()
            val_total += labels.size(0)

    val_loss = val_loss_sum / val_total
    val_acc = val_correct / val_total

    print(
        f"Epoch {epoch+1:02d}/{EPOCHS} | "
        f"Train Acc: {train_acc*100:.2f}% | "
        f"Val Acc: {val_acc*100:.2f}% | "
        f"Val Loss: {val_loss:.4f} | "
        f"Time: {(time.time()-start)/60:.1f} min"
    )

    if val_acc > best_val_acc:
        best_val_acc = val_acc
        best_state = copy.deepcopy(model.state_dict())

        torch.save({
            "model_state": best_state,
            "classes": folder_names,
            "emotions": emotion_names
        }, MODEL_PATH)

        print("  Best validation checkpoint saved.")

print("\nBest validation accuracy:",
      round(best_val_acc * 100, 2), "%")

# ---------------- LOAD BEST MODEL ----------------

checkpoint = torch.load(
    MODEL_PATH, map_location=device, weights_only=False
)
model.load_state_dict(checkpoint["model_state"])
model.eval()

with open(LABEL_PATH, "w") as f:
    json.dump(emotion_names, f)

# ---------------- FINAL TEST EVALUATION ----------------

all_true = []
all_pred = []

with torch.no_grad():
    for images, labels in test_loader:
        images = images.to(device, non_blocking=True)

        with torch.autocast(
            device_type=device.type,
            dtype=torch.float16,
            enabled=use_amp
        ):
            outputs = model(images)

        predictions = outputs.argmax(1).cpu().numpy()

        all_pred.extend(predictions.tolist())
        all_true.extend(labels.numpy().tolist())

test_accuracy = np.mean(
    np.array(all_true) == np.array(all_pred)
)

print("\nFINAL TEST ACCURACY:",
      round(test_accuracy * 100, 2), "%")

print("\nPer-class results:")
print(classification_report(
    all_true,
    all_pred,
    labels=list(range(len(emotion_names))),
    target_names=emotion_names,
    zero_division=0
))

cm = confusion_matrix(
    all_true,
    all_pred,
    labels=list(range(len(emotion_names)))
)

plt.figure(figsize=(8, 7))
plt.imshow(cm, cmap="Blues")
plt.xticks(
    range(len(emotion_names)),
    emotion_names, rotation=45, ha="right"
)
plt.yticks(range(len(emotion_names)), emotion_names)
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("EMPATHICA Test Confusion Matrix")
plt.colorbar()

for i in range(len(emotion_names)):
    for j in range(len(emotion_names)):
        plt.text(j, i, str(cm[i, j]),
                 ha="center", va="center")

plt.tight_layout()
plt.show()

