import cv2
from google.colab import files

def predict_emotion(image_path):
    image = cv2.imread(image_path)

    if image is None:
        print("Could not read image.")
        return None

    rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    detector = cv2.CascadeClassifier(
        cv2.data.haarcascades +
        "haarcascade_frontalface_default.xml"
    )

    faces = detector.detectMultiScale(
        gray, scaleFactor=1.1,
        minNeighbors=5, minSize=(40, 40)
    )

    if len(faces):
        x, y, w, h = max(
            faces, key=lambda f: f[2] * f[3]
        )
        px, py = int(w * 0.10), int(h * 0.10)

        x1, y1 = max(0, x-px), max(0, y-py)
        x2 = min(rgb.shape[1], x+w+px)
        y2 = min(rgb.shape[0], y+h+py)

        face = rgb[y1:y2, x1:x2]
        print("Face detected.")
    else:
        print("No face detected; using full image.")
        face = rgb

    pil_image = Image.fromarray(face)

    # Exact evaluation preprocessing.
    tensor = eval_transform(pil_image).unsqueeze(0).to(device)

    model.eval()
    with torch.no_grad():
        with torch.autocast(
            device_type=device.type,
            dtype=torch.float16,
            enabled=use_amp
        ):
            logits = model(tensor)

        probs = torch.softmax(logits.float(), dim=1)[0].cpu().numpy()

    top = np.argsort(probs)[::-1][:3]
    best = int(top[0])

    plt.figure(figsize=(5, 5))
    plt.imshow(face)
    plt.axis("off")
    plt.title(
        f"{emotion_names[best]} "
        f"({probs[best]*100:.1f}% model score)"
    )
    plt.show()

    print("Top predictions:")
    for i in top:
        print(f"{emotion_names[i]}: {probs[i]*100:.2f}%")

    return {
        "emotion": emotion_names[best],
        "confidence": float(probs[best])
    }

